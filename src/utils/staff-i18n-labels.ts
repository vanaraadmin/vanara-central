export function translateStaffLabel(label: string, translate: Translate): string {
  const normalized = label.trim();
  const assigned = /^Assigned to (.+)$/i.exec(normalized);
  if (assigned?.[1]) return translate("assignedToName", { name: assigned[1] });
  const activeTickets = /^(\d+) active tickets?$/i.exec(normalized);
  if (activeTickets?.[1]) return translate("activeTickets", { count: Number(activeTickets[1]) });
  const key = roomLabelKeys[normalized.toUpperCase()];
  return key ? translate(key) : label;
}
